# ------------------------------------------------------------------------------------------------ helpers
def when(value):
    """ISO string or epoch (s / ms) -> 'YYYY-MM-DD HH:MM UTC'."""
    if value in (None, ""):
        return "n/a"
    try:
        if isinstance(value, (int, float)) or str(value).isdigit():
            seconds = float(value) / (1000 if float(value) > 1e11 else 1)
            return datetime.fromtimestamp(seconds, timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
        return datetime.fromisoformat(str(value).replace("Z", "+00:00")).astimezone(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    except ValueError:
        return "n/a"


def pct(part, whole):
    return f"{100 * part / whole:.2f}%" if whole else "n/a"


def ranges(numbers):
    """[3,4,5,9] -> '3-5, 9'."""
    out, start, prev = [], None, None
    for n in sorted(numbers):
        if start is None:
            start = prev = n
        elif n == prev + 1:
            prev = n
        else:
            out.append(f"{start}-{prev}" if prev != start else str(start))
            start = prev = n
    if start is not None:
        out.append(f"{start}-{prev}" if prev != start else str(start))
    return ", ".join(out)


def table(header, rows):
    return ["| " + " | ".join(header) + " |", "| " + " | ".join("---" for _ in header) + " |"] + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]


def write(name, lines):
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, name), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines).rstrip("\n") + "\n")


def junit_run(path):
    p = os.path.join(RAW, *path)
    if not os.path.exists(p):
        return "n/a"
    root = ET.parse(p).getroot()
    suite = root if root.tag == "testsuite" else root.find("testsuite")
    return when(suite.get("timestamp")) if suite is not None else "n/a"


def package_of(classname):
    """tests.profile.test_profile -> profile."""
    parts = classname.split(".")
    return parts[1] if len(parts) > 1 else parts[0]


