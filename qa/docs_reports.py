def unit_report(results):
    L = ["# Unit Test Report", "", HEADER, ""]
    L += ["## Summary", ""]
    rows = []
    for label, cases, src in (("Backend: unit and API tests", results.unit, ("unit", "junit.xml")),
                              ("Frontend: component logic", results.vitest, ("unit", "frontend-junit.xml"))):
        if cases is None:
            rows.append((label, "not run", "", "", "", "", "", ""))
            continue
        c = collections.Counter(x["status"] for x in cases)
        rows.append((label, "PyTest 9 against MySQL 8" if "Backend" in label else "Vitest 4", len(cases), c["passed"], c["failed"], c["skipped"],
                     f"{sum(x['time'] for x in cases):.1f} s", junit_run(src)))
    L += table(["Suite", "Tool", "Tests", "Passed", "Failed", "Skipped", "Duration", "Run at"], rows)
    L += ["", "The backend tests call the real Flask application through its test client against a real MySQL 8 database "
          "(READ COMMITTED, as in production), so the SQL, constraints, transactions and role checks are exercised, not mocked.", ""]

    L += ["## Backend tests by feature package", ""]
    if results.unit is None:
        L += ["Not run.", ""]
    else:
        groups = collections.defaultdict(list)
        for c in results.unit:
            groups[package_of(c["suite"])].append(c)
        rows = []
        for pkg in sorted(groups, key=lambda p: (STORY.get(p, "~"), p)):
            cs = groups[pkg]
            negative = sum(1 for c in cs if "negative" in c["suite"])
            rows.append((STORY.get(pkg, ""), f"`{pkg}`", len(cs), sum(c["status"] == "passed" for c in cs), sum(c["status"] == "failed" for c in cs), negative))
        rows.append(("**Total**", "", len(results.unit), sum(c["status"] == "passed" for c in results.unit), sum(c["status"] == "failed" for c in results.unit),
                     sum(1 for c in results.unit if "negative" in c["suite"])))
        L += table(["Story", "Package (`backend/tests/...`)", "Tests", "Passed", "Failed", "Tests in `*_negative` modules"], rows)
        L += ["", "_The last column counts the tests in the dedicated `*_negative.py` modules (invalid input, forbidden roles, malformed payloads, repeated or conflicting requests). Every other module also contains rejection and permission tests._", ""]

    L += ["## Frontend tests by file", ""]
    if results.vitest is None:
        L += ["Not run.", ""]
    else:
        groups = collections.defaultdict(list)
        for c in results.vitest:
            groups[c["suite"]].append(c)
        L += table(["Test file (`frontend/...`)", "Tests", "Passed", "Failed"],
                   [(f"`{f}`", len(cs), sum(c["status"] == "passed" for c in cs), sum(c["status"] == "failed" for c in cs)) for f, cs in sorted(groups.items())])
        L += [""]

    L += ["## Failed or skipped tests", ""]
    bad = [c for c in (results.unit or []) + (results.vitest or []) if c["status"] != "passed"]
    L += (table(["Suite", "Test", "Status"], [(c["suite"], c["name"], c["status"]) for c in bad]) if bad else ["None."])
    L += ["", "Coverage of these tests: see `CODE-COVERAGE-REPORT.md` and `BRANCH-COVERAGE-REPORT.md`. "
          "Frontend coverage is not measured; the user interface is validated by the Playwright suites in `SYSTEM-VALIDATION-REPORT.md`.", ""]
    write("UNIT-TEST-REPORT.md", L)


