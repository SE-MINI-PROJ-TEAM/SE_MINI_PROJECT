def uat_numbers():
    path = os.path.join(ROOT, "docs", "uat", "UAT-RESULTS.md")
    if not os.path.exists(path):
        return None
    text = open(path, encoding="utf-8").read()
    rows = re.findall(r"^\| (US-\d+\.\d+) \|.*?\|\s*(PASS|FAIL|BLOCKED)?\s*\|", text, re.M)
    return collections.Counter(r for _, r in rows), len(rows)


def uat_titles(uat_json):
    """Titles of every spec in the Playwright UAT results (one per acceptance criterion or exploratory charter)."""
    titles = []

    def walk(suite):
        titles.extend(spec["title"] for spec in suite.get("specs", []))
        for child in suite.get("suites", []):
            walk(child)

    for top in uat_json["suites"]:
        walk(top)
    return titles


