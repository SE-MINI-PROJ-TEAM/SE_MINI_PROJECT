# ------------------------------------------------------------------------------------------------ coverage reports
def coverage_data():
    path = os.path.join(RAW, "unit", "coverage.xml")
    if not os.path.exists(path):
        return None
    root = ET.parse(path).getroot()
    source = (root.findtext("sources/source") or "").replace("\\", "/").rstrip("/").split("/")[-1] or "app"
    files = []
    for cls in root.iter("class"):
        lines = [(int(l.get("number")), int(l.get("hits")), l.get("condition-coverage") if l.get("branch") == "true" else None) for l in cls.find("lines")]
        name = cls.get("filename").replace("\\", "/")
        branches = [(n, *map(int, re.search(r"\((\d+)/(\d+)\)", cc).groups())) for n, _, cc in lines if cc]
        files.append({"name": name, "group": os.path.dirname(name) or "(app root)", "statements": len(lines), "missing": [n for n, h, _ in lines if h == 0],
                      "branches": sum(t for _, _, t in branches), "covered": sum(c for _, c, _ in branches), "partial": [n for n, c, t in branches if c < t]})
    return {"root": root, "source": source, "files": sorted(files, key=lambda f: f["name"]), "run": when(root.get("timestamp"))}


def coverage_reports():
    data = coverage_data()
    if data is None:
        return
    files, source, run = data["files"], data["source"], data["run"]
    prefix = f"backend/{source}/"
    st = sum(f["statements"] for f in files)
    miss = sum(len(f["missing"]) for f in files)
    bt = sum(f["branches"] for f in files)
    bc = sum(f["covered"] for f in files)
    groups = collections.defaultdict(list)
    for f in files:
        groups[f["group"]].append(f)

    # ---- line coverage
    L = ["# Code Coverage Report (line coverage)", "", HEADER, "",
         f"Backend measured with `coverage.py` while the PyTest suite ran. Run at **{run}**. The gate is **70%** (`SYS-NF-005`).", "",
         "## Overall", ""]
    L += table(["Statements", "Covered", "Missed", "Line coverage", "Gate (>= 70%)"],
               [(st, st - miss, miss, f"**{pct(st - miss, st)}**", "PASS" if st and 100 * (st - miss) / st >= 70 else "FAIL")])
    L += ["", "## By package", ""]
    rows = []
    for g in sorted(groups):
        fs = groups[g]
        s = sum(f["statements"] for f in fs)
        m = sum(len(f["missing"]) for f in fs)
        rows.append((f"`{prefix}{g}`" if g != "(app root)" else f"`{prefix}`", STORY.get(os.path.basename(g), ""), len(fs), s, m, pct(s - m, s)))
    L += table(["Package", "Story", "Files", "Statements", "Missed", "Line coverage"], rows)
    L += ["", "## By file", ""]
    L += table(["File", "Statements", "Missed", "Line coverage", "Lines not executed"],
               [(f"`{prefix}{f['name']}`", f["statements"], len(f["missing"]), pct(f["statements"] - len(f["missing"]), f["statements"]), ranges(f["missing"]) or "none") for f in files])
    L += ["", "## Scope", "",
          "- Measured: the Flask backend (`backend/app`), which holds the business rules, security and persistence.",
          "- Not measured: the React frontend. Its logic is covered by the Vitest suite, and the screens by the Playwright suites (`SYSTEM-VALIDATION-REPORT.md`).",
          f"- {miss} of {st:,} statements are not executed by the suite. Each one is listed by line number in the table above.", ""]
    write("CODE-COVERAGE-REPORT.md", L)

    # ---- branch coverage
    L = ["# Branch Coverage Report", "", HEADER, "",
         f"Backend measured with `coverage.py` in branch mode (`branch = True`) while the PyTest suite ran. Run at **{run}**. "
         "A branch is one outcome of a decision (for example the `if` taken and the `if` skipped).", "", "## Overall", ""]
    L += table(["Branches", "Covered", "Missed", "Branch coverage"], [(bt, bc, bt - bc, f"**{pct(bc, bt)}**")])
    L += ["", "## By package", ""]
    rows = []
    for g in sorted(groups):
        fs = groups[g]
        t = sum(f["branches"] for f in fs)
        c = sum(f["covered"] for f in fs)
        rows.append((f"`{prefix}{g}`" if g != "(app root)" else f"`{prefix}`", STORY.get(os.path.basename(g), ""), t, c, t - c, pct(c, t)))
    L += table(["Package", "Story", "Branches", "Covered", "Missed", "Branch coverage"], rows)
    L += ["", "## By file", ""]
    L += table(["File", "Branches", "Covered", "Branch coverage", "Lines with a branch not taken"],
               [(f"`{prefix}{f['name']}`", f["branches"], f["covered"], pct(f["covered"], f["branches"]), ranges(f["partial"]) or "none") for f in files if f["branches"]])
    L += ["", "## Notes", "",
          "- Files without any decision (for example constants and empty `__init__.py` modules) are not listed.",
          "- Branch coverage is stricter than line coverage: a line can run while only one of its outcomes was ever taken.", ""]
    write("BRANCH-COVERAGE-REPORT.md", L)


