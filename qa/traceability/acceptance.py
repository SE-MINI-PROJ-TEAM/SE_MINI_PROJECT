"""Build and verify the acceptance-criteria traceability matrix.

    python qa/traceability/acceptance.py            # writes docs/uat/ACCEPTANCE-MATRIX.md, exits 1 on any gap
    python qa/traceability/acceptance.py --check    # verify only (CI)

For every "- [ ]" criterion in stories.md it requires at least one automated check, and verifies that each
referenced test / Newman folder / E2E title / unit-test file really exists.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(__file__)
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, HERE)
from acceptance_map import ACCEPTANCE  # noqa: E402

STORIES = os.path.join(ROOT, "stories.md")
OUT = os.path.join(ROOT, "docs", "uat", "ACCEPTANCE-MATRIX.md")


def parse_stories():
    """{ 'US-01': {'title':..., 'role':..., 'sprint':..., 'assignee': ..., 'criteria': [...], 'srs': ..., 'tc': ...} }"""
    text = open(STORIES, encoding="utf-8").read()
    stories = {}
    for block in re.split(r"\n(?=### US-\d+:)", text)[1:]:
        head = re.match(r"### (US-\d+): (.+)", block)
        sid, title = head.group(1), head.group(2).strip()
        field = lambda label: (re.search(rf"\*\s*\*\*{label}:\*\*\s*(.+)", block) or [None, ""])[1].strip()
        criteria = re.findall(r"^- \[[ x]\] (.+)$", block.split("### Acceptance Criteria")[1].split("### Requirement Traceability")[0], re.M)
        story_line = re.search(r"### User Story\s*\n(.+)", block).group(1).strip()
        srs = re.search(r"\*\*SRS ID:\*\* (.+)", block).group(1).strip()
        tcs = re.search(r"\*\*Test Case ID:\*\* (.+)", block).group(1).strip()
        stories[sid] = {
            "title": title, "sprint": field("Sprint Allocation"), "assignee": field("Assignee"), "story": story_line,
            "criteria": criteria, "srs": srs.replace("`", ""), "tc": tcs.replace("`", ""),
        }
    return stories


def read(path):
    full = os.path.join(ROOT, path)
    return open(full, encoding="utf-8").read() if os.path.exists(full) else None


def collection_folders():
    path = os.path.join(ROOT, "qa", "newman", "collection.json")
    if not os.path.exists(path):
        import subprocess
        subprocess.run([sys.executable, os.path.join(ROOT, "qa", "newman", "build_collection.py")], check=True, capture_output=True)
    return [f["name"] for f in json.load(open(path, encoding="utf-8"))["item"]]


def verify_reference(ref, folders):
    kind, target, name = ref
    if kind == "py":
        text = read(target)
        return text is not None and re.search(rf"^def {re.escape(name)}\(", text, re.M) is not None
    if kind == "e2e":
        text = read(target)
        return text is not None and name in text
    if kind == "vitest":
        return read(target) is not None
    if kind == "newman":
        return any(f.startswith(target) for f in folders)
    if kind == "k6":
        return f"scenario:{target}" in (read("qa/k6/load.js") or "")
    if kind == "zap":
        return os.path.exists(os.path.join(ROOT, "qa", "zap", "rules.conf"))
    return False


def label(ref):
    kind, target, name = ref
    if kind == "py":
        return f"pytest `{os.path.basename(target)}::{name}`"
    if kind == "e2e":
        return f"Playwright `{os.path.basename(target)}` \"{name}\""
    if kind == "vitest":
        return f"Vitest `{os.path.basename(target)}`"
    if kind == "newman":
        return f"Newman folder \"{target}…\""
    if kind == "k6":
        return f"k6 scenario `{target}`"
    return target


def main():
    stories = parse_stories()
    folders = collection_folders()
    problems = []
    rows = []
    for sid, story in stories.items():
        mapping = ACCEPTANCE.get(sid)
        if mapping is None:
            problems.append(f"{sid}: no entry in acceptance_map.py")
            continue
        if len(mapping) != len(story["criteria"]):
            problems.append(f"{sid}: stories.md has {len(story['criteria'])} criteria but the map lists {len(mapping)}")
            continue
        for n, (criterion, refs) in enumerate(zip(story["criteria"], mapping), 1):
            if not refs:
                problems.append(f"{sid}.{n}: no automated check for \"{criterion}\"")
            for ref in refs:
                if not verify_reference(ref, folders):
                    problems.append(f"{sid}.{n}: stale reference {ref}")
            rows.append((sid, n, story, criterion, refs))

    if problems:
        print("ACCEPTANCE TRACEABILITY PROBLEMS:\n  " + "\n  ".join(problems))
        sys.exit(1)

    total = len(rows)
    print(f"Acceptance traceability OK: {total} criteria across {len(stories)} stories, every one covered by an automated check.")
    if "--check" in sys.argv:
        return

    lines = [
        "# Acceptance criteria traceability matrix",
        "",
        "_Generated by `qa/traceability/acceptance.py` from `stories.md` and `qa/traceability/acceptance_map.py`. Do not edit by hand._",
        "",
        f"**{total} acceptance criteria · {len(stories)} user stories · every criterion is covered by at least one automated check.**",
        "Manual confirmation of each criterion by the customer is recorded in `docs/uat/UAT-RESULTS.md`.",
        "",
    ]
    for sid, story in stories.items():
        lines += [f"## {sid} — {story['title']}", "", f"{story['sprint']} · {story['assignee']} · SRS {story['srs']} · Tests {story['tc']}", "",
                  "| # | Acceptance criterion | Automated evidence |", "| --- | --- | --- |"]
        for r_sid, n, _, criterion, refs in rows:
            if r_sid == sid:
                lines.append(f"| {sid}.{n} | {criterion} | " + "<br>".join(label(r) for r in refs) + " |")
        lines.append("")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"Wrote {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
