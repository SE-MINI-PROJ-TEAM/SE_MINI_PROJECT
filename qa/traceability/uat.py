"""Generate the User Acceptance Test script and (once) the blank results sheet.

    python qa/traceability/uat.py            # (re)writes docs/uat/UAT-SCRIPT.md; creates UAT-RESULTS.md only if missing
    python qa/traceability/uat.py --force    # also overwrites UAT-RESULTS.md (this DISCARDS recorded results)

UAT-SCRIPT.md is derived from stories.md (criteria) and docs/SMOKE_TEST.md (click-by-click steps) so the three
documents cannot disagree. UAT-RESULTS.md is the only file humans edit.
"""
import os
import re
import sys

HERE = os.path.dirname(__file__)
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, HERE)
from acceptance import parse_stories  # noqa: E402

UAT = os.path.join(ROOT, "docs", "uat")
ACCOUNT = {
    "Administrator": "admin001@srs.edu", "Faculty Member": "faculty001@srs.edu", "Student": "student001@srs.edu",
    "New User": "new.student@srs.edu (temporary password Temp@12345)",
    "Student or Faculty Member": "student001@srs.edu and faculty001@srs.edu",
    "Faculty Member and Administrator": "faculty001@srs.edu then admin001@srs.edu",
    "Student or Faculty": "student001@srs.edu and faculty001@srs.edu",
}


def smoke_steps():
    text = open(os.path.join(ROOT, "docs", "SMOKE_TEST.md"), encoding="utf-8").read()
    steps = {}
    for m in re.finditer(r"^### (US-\d+) [—-] .*?\n(.*?)(?=^#{2,3} |\Z)", text, re.M | re.S):
        steps[m.group(1)] = m.group(2).strip()
    return steps


def role_of(story_line):
    m = re.match(r"As an? (.+?), I want", story_line)
    return m.group(1) if m else "User"


def script(stories, steps):
    lines = [
        "# UAT script",
        "",
        "_Generated by `qa/traceability/uat.py` from `stories.md` and `docs/SMOKE_TEST.md`. Record outcomes in `UAT-RESULTS.md`; do not edit this file._",
        "",
        "## Before you start",
        "",
        "1. Start the application (`dev.ps1`) against a freshly seeded database: `cd backend; ..\\.venv\\Scripts\\python manage.py seed --reset`.",
        "2. Open <http://localhost:5173>. All demo accounts use the password `Password@123` (except the new user, see US-02).",
        "3. Work through the stories in order — later stories reuse data created by earlier ones (for example the account created in US-01).",
        "4. For every acceptance criterion record **PASS**, **FAIL** or **BLOCKED** in `UAT-RESULTS.md` with the criterion ID (e.g. `US-08.4`).",
        "   Log every FAIL as a defect (GitHub issue, label `uat`) and write the issue number in the results sheet.",
        "",
        "Severity: **Critical** (data loss / security / cannot continue) · **High** (acceptance criterion not met) · **Medium** (works but wrong / confusing) · **Low** (cosmetic).",
        "",
    ]
    for sid, s in stories.items():
        role = role_of(s["story"])
        lines += [
            f"## {sid} — {s['title']}", "",
            f"**{s['sprint']}** · Sign in as: {ACCOUNT.get(role, role)}", "",
            f"> {s['story']}", "",
        ]
        if sid in steps:
            lines += ["**Steps**", "", steps[sid], ""]
        lines += ["**Verify (acceptance criteria)**", ""]
        lines += [f"- **{sid}.{n}** {c}" for n, c in enumerate(s["criteria"], 1)]
        lines.append("")
    return "\n".join(lines)


def results(stories):
    lines = [
        "# UAT results",
        "",
        "| Field | Value |",
        "| --- | --- |",
        "| Application version / commit | |",
        "| Test environment | |",
        "| Tester(s) | |",
        "| Date(s) | |",
        "",
        "Result values: `PASS` · `FAIL` · `BLOCKED` (leave empty if not yet executed).",
        "",
        "## Acceptance criteria",
        "",
        "| ID | Acceptance criterion | Result | Defect # | Comment |",
        "| --- | --- | --- | --- | --- |",
    ]
    for sid, s in stories.items():
        for n, c in enumerate(s["criteria"], 1):
            lines.append(f"| {sid}.{n} | {c} | | | |")
    lines += [
        "",
        "## Exploratory sessions",
        "",
        "Time-boxed (15 min each). Write down anything surprising, even if it is not a defect.",
        "",
        "| Charter | Tester | Findings / defects |",
        "| --- | --- | --- |",
        "| Try to break the grade lifecycle as a **student** (skip states, dispute twice, read other students' marks) | | |",
        "| Try to see or change **another faculty member's** sections, rosters and marks | | |",
        "| Use the whole app with the **keyboard only** (no mouse), then at **375 px** width | | |",
        "| Enter **hostile input** in every text field (very long text, `<script>`, quotes, emoji, negative numbers) | | |",
        "| Run **two sessions at once** (two browsers) and edit the same attendance sheet / grade sheet | | |",
        "",
        "## Defect log",
        "",
        "| Issue # | Criterion | Severity | Summary | Status |",
        "| --- | --- | --- | --- | --- |",
        "| | | | | |",
        "",
        "## Sign-off",
        "",
        "The undersigned has witnessed the execution above and accepts the system as ☐ **accepted** · ☐ **accepted with conditions** · ☐ **rejected**.",
        "",
        "Conditions / remarks:",
        "",
        "| Role | Name | Signature | Date |",
        "| --- | --- | --- | --- |",
        "| Customer / Course Instructor | Dr. Adithya Balasubramanyam | | |",
        "| QA Lead | Vibha Vasisht | | |",
        "| Test Engineer | Uttam B S | | |",
        "| Developer | Tanmay T A | | |",
        "",
    ]
    return "\n".join(lines)


def main():
    stories = parse_stories()
    os.makedirs(UAT, exist_ok=True)
    with open(os.path.join(UAT, "UAT-SCRIPT.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write(script(stories, smoke_steps()))
    print("Wrote docs/uat/UAT-SCRIPT.md")
    target = os.path.join(UAT, "UAT-RESULTS.md")
    if "--force" in sys.argv or not os.path.exists(target):
        with open(target, "w", encoding="utf-8", newline="\n") as f:
            f.write(results(stories))
        print("Wrote docs/uat/UAT-RESULTS.md (blank sheet)")
    else:
        print("docs/uat/UAT-RESULTS.md already exists - left untouched (use --force to reset)")


if __name__ == "__main__":
    main()
